-- ============================================================
-- DECISION: tags live in question_bank.tags_json (no question_bank_tags table)
-- ------------------------------------------------------------
-- Tags here are a small, low-cardinality, read-mostly Arabic taxonomy
-- (النحو / البلاغة / الأدب ...). A join table would add two extra writes per
-- tag on every create/update plus a JOIN + GROUP_CONCAT on every list query,
-- for data that is never queried on its own. Storing them as a JSON array
-- keeps create/update/export/import a single-row operation (lossless
-- round-trip for backup) and filtering is a bound-parameter LIKE on the
-- serialised array:  tags_json LIKE '%"' || ? || '"%'
-- If tag analytics (counts, autocomplete ranking, cross-tag facets) becomes a
-- product requirement, a question_bank_tags table can be back-filled from
-- tags_json without a breaking API change.
-- ============================================================
